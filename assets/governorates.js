// ============================================================================
// المصدر الوحيد للمحافظات والولايات
//
// أداة القبلة (الأداة الأولى) لا تحتفظ بقائمة ثابتة؛ فهي تملأ حقل "المحافظة
// والولاية" تلقائياً من خدمة العناوين ثم تحفظ القيمة مع كل مسجد في MosqueStore.
// لذلك المصدر الحقيقي القائم هو: محافظات عُمان الرسمية + كل قيمة سبق أن سُجّلت
// فعلياً من الأداة الأولى. هذه الوحدة تجمع الاثنين في مكان واحد، فأي تغيير
// مستقبلي (محافظة جديدة أو صيغة تسمية مختلفة) ينعكس على كل الأدوات تلقائياً.
// ============================================================================

(function () {
  "use strict";

  // محافظات سلطنة عُمان الإحدى عشرة
  const OFFICIAL = [
    "محافظة مسقط",
    "محافظة ظفار",
    "محافظة مسندم",
    "محافظة البريمي",
    "محافظة الداخلية",
    "محافظة شمال الباطنة",
    "محافظة جنوب الباطنة",
    "محافظة جنوب الشرقية",
    "محافظة شمال الشرقية",
    "محافظة الظاهرة",
    "محافظة الوسطى",
  ];

  // يستخرج اسم المحافظة من قيمة قد تكون "محافظة كذا - ولاية كذا"
  function governorateOf(value) {
    if (!value) return "";
    return String(value).split(" - ")[0].trim();
  }

  // القائمة النهائية = الرسمية + ما سجّلته الأداة الأولى فعلياً (بلا تكرار)
  function list() {
    const seen = new Set();
    const out = [];

    const push = (v) => {
      const name = governorateOf(v);
      if (!name) return;
      const key = name.replace(/^محافظة\s+/, "");
      if (seen.has(key)) return;
      seen.add(key);
      out.push(name);
    };

    OFFICIAL.forEach(push);

    // القيم القادمة من الأداة الأولى (إن وُجد المخزن)
    if (window.MosqueStore && typeof window.MosqueStore.loadAll === "function") {
      try {
        window.MosqueStore.loadAll().forEach((m) => push(m.governorate));
      } catch (e) {
        // المخزن غير متاح — نكتفي بالقائمة الرسمية
      }
    }

    return out;
  }

  window.Governorates = { list, governorateOf, OFFICIAL };
})();
