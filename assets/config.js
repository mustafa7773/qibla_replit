window.SkyConfig = {
  // اتركه فارغاً إن كنت تعتمد على قاعدة البيانات المركزية (api/records)
  syncEndpoint: "",

  // مفتاح مشترك اختياري. إن ضبطته هنا فاضبط نفس القيمة في Vercel باسم
  // SKY_API_KEY. اتركه فارغاً ليعمل كل شيء بلا مفتاح.
  apiKey: "",
};

// تحقق صريح عند الإقلاع: الفشل الصامت أسوأ من الانهيار.
// كان هذا الملف يحتوي خطأً نحوياً يمنع تحميله كاملاً دون أي إشعار.
(function verifyConfig() {
  if (!window.SkyConfig || typeof window.SkyConfig !== "object") {
    console.error("[Sky] config.js لم يُحمّل — window.SkyConfig غير معرّف.");
    return;
  }
  const ep = window.SkyConfig.syncEndpoint;
  if (ep && !/^https:\/\//i.test(ep)) {
    console.error("[Sky] رابط المزامنة يجب أن يبدأ بـ https:// — القيمة الحالية:", ep);
  }
})();
